import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { jsxControls } from './telemetry-jsx.mjs';
import { componentControlIds } from '../shared/telemetry-controls.js';

const root = fileURLToPath(new URL('..', import.meta.url));
async function files(directory) {
  const result = [];
  for (const item of await readdir(resolve(root, directory), { withFileTypes: true })) {
    const path = `${directory}/${item.name}`;
    if (item.isDirectory()) result.push(...(await files(path)));
    else if (/\.(?:[jt]sx?|html)$/.test(path)) result.push(path);
  }
  return result.sort();
}

export async function telemetryCatalog() {
  const paths = (
    await Promise.all(['frontend', 'shared', 'src', 'functions', 'warranty-verifier'].map(files))
  ).flat();
  const controls = new Set(),
    codes = new Set(),
    routes = [],
    missing = [];
  for (const path of paths) {
    if (path === 'shared/telemetry-catalog.js') continue;
    const source = await readFile(resolve(root, path), 'utf8');
    for (const match of source.matchAll(
      /data-track=(?:["']([a-z][a-z0-9.-]+)["']|([a-z][a-z0-9.-]+))/g
    ))
      controls.add(match[1] || match[2]);
    for (const match of source.matchAll(
      /setAttribute\(['"]data-track['"],\s*['"]([a-z][a-z0-9.-]+)['"]\)/g
    ))
      controls.add(match[1]);
    if (/\.[jt]sx$/.test(path)) {
      for (const control of jsxControls(source)) {
        if (control.id) {
          if (!/^[a-z][a-z0-9.-]+$/.test(control.id))
            missing.push(`${path}:${control.line} invalid ID`);
          for (const id of componentControlIds(control.tag, control.id)) controls.add(id);
        } else if (
          !/^(?:trackId|controlPart\(trackId, ['"][a-z]+['"]\))$/.test(control.expression)
        ) {
          missing.push(
            `${path}:${control.line} ${control.tag} requires a static ID or validated component part`
          );
        }
      }
    } else if (/^(?:frontend|warranty-verifier)\//.test(path) || path.startsWith('shared/')) {
      // Native controls in JSX, HTML and HTML templates must have explicit,
      // source-owned IDs. IDs never depend on a label, input or record value.
      for (const match of source.matchAll(
        /<(?:button|a|input|select|textarea|form|dialog|details|summary)\b[^>]*>/g
      )) {
        if (!/data-track=/.test(match[0]))
          missing.push(`${path}:${source.slice(0, match.index).split('\n').length}`);
      }
    }
    for (const match of source.matchAll(
      /\b([A-Za-z_$][\w$]*)\s*=\s*document\.createElement\(['"](button|input|select|textarea|form|dialog|details|summary|a)['"]\)/g
    )) {
      const setter = new RegExp(`${match[1]}\\.setAttribute\\(['"]data-track['"]`);
      if (!setter.test(source))
        missing.push(`${path}: dynamic ${match[1]} needs a source-owned ID`);
    }
    if (path.startsWith('src/')) {
      for (const match of source.matchAll(/['"]([A-Z][A-Z0-9]*_[A-Z0-9_]+)['"]/g))
        codes.add(match[1]);
    }
    if (!path.startsWith('src/routes/')) continue;
    for (const match of source.matchAll(
      /\[\s*['"](GET|POST|PUT|PATCH|DELETE|HEAD|OPTIONS)['"]\s*,\s*\//g
    )) {
      let end = match.index + match[0].length,
        inClass = false;
      const start = end;
      for (; end < source.length; end++) {
        if (source[end] === '\\') {
          end++;
          continue;
        }
        if (source[end] === '[') inClass = true;
        if (source[end] === ']') inClass = false;
        if (source[end] === '/' && !inClass) break;
      }
      const pattern = source.slice(start, end);
      const module = path.split('/').at(-1).replace('.js', '');
      routes.push({
        id: `${module}.${match[1].toLowerCase()}.${createHash('sha256').update(pattern).digest('hex').slice(0, 8)}`,
        method: match[1],
        pattern
      });
    }
  }
  if (missing.length) throw new Error(`Missing stable telemetry IDs:\n${missing.join('\n')}`);
  return (
    '// Generated by scripts/telemetry-catalog.mjs; IDs in source are the source of truth.\n' +
    `export const CONTROL_IDS = ${JSON.stringify([...controls].sort(), null, 2)};\n` +
    `export const ROUTE_DEFINITIONS = ${JSON.stringify(routes, null, 2)};\n` +
    `export const ERROR_CODES = ${JSON.stringify([...codes].sort(), null, 2)};\n` +
    `export const SOURCE_FILES = ${JSON.stringify(paths.filter((path) => /\.[jt]sx?$/.test(path) && path !== 'shared/telemetry-catalog.js').sort(), null, 2)};\n`
  );
}

if (
  process.argv[1] &&
  relative(root, resolve(process.argv[1])) === 'scripts/telemetry-catalog.mjs'
) {
  const path = resolve(root, 'shared/telemetry-catalog.js');
  const generated = await telemetryCatalog();
  if (process.argv.includes('--check')) {
    if ((await readFile(path, 'utf8')) !== generated)
      throw new Error('Refresh the telemetry catalogue with npm run telemetry:catalog.');
    console.log('Telemetry control and route coverage verified.');
  } else await writeFile(path, generated);
}

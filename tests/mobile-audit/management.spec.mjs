test('lead-real-transfer-correction-history', async ({ page, request, audit }, info) => {
  const office = await loginApi(request, '20261001');
  const tech = await loginApi(request, '20261002');
  const recipient = await loginApi(request, '20261003');
  const home = await api(request, '/api/field/home', office.token);
  const credential = await api(request, `/api/attendance/events/${home.event.id}/token`, office.token, { revision: home.event.revision });
  for (const session of [tech, recipient]) await api(request, '/api/attendance/check-ins', session.token, { token: credential.token, requestId: randomUUID() });
  const order = await orderFixture(request, office.token, info);
  const photos = [];
  for (const side of ['front', 'back']) photos.push(await api(request, `/api/appointments/${order.id}/attachments`, tech.token, { filename: `${side}.png`, mimeType: 'image/png', data: PHOTO.toString('base64'), purpose: `intake_${side}` }));
  await api(request, `/api/appointments/${order.id}/status`, tech.token, { status: 'in_progress', revision: order.revision, frontPhotoId: photos[0].id, backPhotoId: photos[1].id, verification: { brand: '联想', model: 'ThinkPad Mobile', warranty: 'expired', liquidMetal: 'no', note: '' }, requestId: randomUUID() }, 'PATCH');
  await login(page, '20261004');
  await navigate(page, '现场工作台');
  await page.locator('.field-order').filter({ hasText: order.id }).click();
  await page.getByRole('button', { name: '转交其他维修人员', exact: true }).click();
  await page.getByRole('combobox', { name: '接手人员', exact: true }).selectOption('20261003');
  await page.getByLabel('交接原因', { exact: true }).fill('本地移动审查交接给下一位维修人员继续处理');
  fit(await audit.capture('repair-transfer-form', { axe: true }));
  await page.getByRole('button', { name: '确认转交', exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('维修人员：周宁');
  await audit.capture('repair-transfer-success');
  // Complete the transferred order through its real owner before the next project.
  const transferred = await api(request, `/api/field/appointments/${order.id}`, recipient.token);
  await api(request, `/api/appointments/${order.id}/status`, recipient.token, { status: 'completed', revision: transferred.revision, repairNote: '交接后完成检查并验证', outcome: 'repaired', requestId: randomUUID() }, 'PATCH');
  await page.getByRole('dialog').getByRole('button', { name: '关闭', exact: true }).click();
  await navigate(page, '预约记录');
  await page.getByLabel('查找预约', { exact: true }).fill(order.id);
  await expect(page.locator('.records-table tbody tr')).toHaveCount(1);
  await page.locator('.records-table tbody tr button').first().click();
  await page.getByRole('button', { name: '修正预约记录', exact: true }).click();
  await page.getByRole('combobox', { name: '修正后状态', exact: true }).selectOption('cancelled');
  await page.getByLabel('纠错原因', { exact: true }).fill('本地测试核实原登记误记状态，修正为取消');
  fit(await audit.capture('record-correction-form'));
  await page.getByRole('button', { name: '核对修改', exact: true }).click();
  fit(await audit.capture('record-correction-confirm'));
  await page.getByRole('button', { name: '确认修正记录', exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('预约记录已修正');
  await expect(page.getByRole('dialog')).toContainText('已取消');
  await audit.capture('record-correction-history');
  expect((await api(request, `/api/field/appointments/${order.id}`, recipient.token)).status).toBe('cancelled');
});


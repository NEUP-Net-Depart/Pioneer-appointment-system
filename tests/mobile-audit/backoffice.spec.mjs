import { test, expect, api, login, loginApi, navigate } from './support.mjs';
test.skip(process.env.E2E_FIELD !== 'true', 'Requires the disposable field fixture');

test('backoffice-real-member-activation-role-save-and-error-page', async ({ page, request, audit }, info) => {
  const index = ['chromium', 'webkit', 'firefox'].indexOf(info.project.use.browserName) * 5 + [360, 393, 430, 768, 1440].indexOf(info.project.use.viewport.width);
  const sid = String(20800000 + index), name = `后台审查新成员${index}`, edited = `后台审查已编辑成员${index}`;
  await page.goto('/__mobile-audit-no-such-page__');
  await expect(page.getByRole('heading', { name: '页面不存在', exact: true })).toBeVisible();
  await audit.capture('not-found', { axe: true });
  await audit.captureFont200('not-found');
  const root = await loginApi(request);
  await login(page);
  await navigate(page, '成员管理');
  await page.getByRole('button', { name: '导入名单', exact: true }).click();
  const imported = page.getByRole('dialog');
  await imported.getByLabel('名单内容', { exact: true }).fill(`studentId,name,homeCampusId,departmentId,workProfiles,roleCodes,authorizedCampuses,accountRole\n${sid},${name},campus-nanhu,dept-office,office,office,campus-nanhu,technician`);
  await imported.getByRole('button', { name: '预览并核对', exact: true }).click();
  await expect(imported).toContainText('待导入 1 名成员');
  await audit.capture('member-import-preview');
  await imported.getByRole('button', { name: '确认名单与培训结果并导入', exact: true }).click();
  await expect(imported).toContainText('已导入 1 名成员');
  await imported.getByRole('button', { name: '完成', exact: true }).click();
  await page.getByRole('textbox', { name: '搜索成员', exact: true }).fill(sid);
  await page.locator('.members-results .react-row').filter({ hasText: sid }).getByRole('button', { name: '编辑成员与权限' }).click();
  await page.getByRole('dialog').getByLabel('姓名', { exact: true }).fill(edited);
  await page.getByRole('dialog').getByRole('button', { name: '保存资料', exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('成员资料已保存');
  await audit.capture('member-profile-saved');
  await page.getByRole('dialog').getByRole('button', { name: '关闭', exact: true }).click();
  await page.goto('/staff/?activate=1');
  await page.locator('#activation-student-id').fill(sid);
  await page.locator('#activation-name').fill(name);
  await page.locator('#activation-campus').selectOption('南湖');
  await page.locator('#activation-password').fill('StaffTest!2026');
  await page.locator('#activation-confirm').fill('StaffTest!2026');
  await page.getByRole('button', { name: '提交激活申请', exact: true }).click();
  await expect(page.locator('#activation-status')).toContainText('等待管理员');
  await audit.capture('activation-pending-result');
  await page.goto('/staff/');
  await expect(page.locator('.field-app:not(.workspace-bootstrap)')).toBeVisible();
  await navigate(page, '账号管理');
  await page.getByRole('button', { name: '激活审核', exact: true }).click();
  await page.getByRole('checkbox', { name: `选择 ${sid}`, exact: true }).check();
  await page.getByLabel('我已逐一核实选中申请的本人身份', { exact: true }).check();
  await audit.capture('activation-review-selected', { axe: true });
  await page.getByRole('button', { name: '批准申请', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: '已处理 1 条申请' })).toBeVisible();
  await audit.capture('activation-approved');
  await page.goto('/staff/?activate=1');
  await expect(page.locator('#activation-status')).toContainText('审核已通过');
  await expect(page.locator('#activation-login')).toBeVisible();
  await audit.capture('activation-approved-entry', { axe: true });
  await page.evaluate(() => sessionStorage.clear());
  await login(page, sid);
  await audit.capture('new-member-login');
  await page.evaluate(() => sessionStorage.clear());
  await login(page);
  const roleName = `移动审查自定义角色${index}`;
  const role = await api(request, '/api/roles', root.token, { code: `mobile_audit_${index}`, name: roleName, grants: [] });
  const definitions = await api(request, '/api/permissions', root.token);
  const definition = definitions.items.find(item => item.code === 'roster.read');
  expect(definition).toBeTruthy();
  await navigate(page, '授权管理');
  await page.getByRole('complementary', { name: '角色列表' }).getByRole('button', { name: new RegExp(roleName) }).click();
  await page.getByRole('searchbox', { name: '查找权限', exact: true }).fill(definition.name);
  await page.locator('.react-permission-item').getByRole('checkbox').first().check();
  await audit.capture('role-permission-draft', { axe: true });
  await page.getByRole('button', { name: '保存权限', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: '权限已保存' })).toBeVisible();
  await audit.capture('role-permission-saved');
  const saved = (await api(request, '/api/roles', root.token)).items.find(item => item.id === role.id);
  expect(saved.grants.some(grant => grant.permissionCode === 'roster.read')).toBe(true);
  await navigate(page, '现场工作台');
  await page.getByRole('button', { name: '展示签到码', exact: true }).click();
  await expect(page.getByRole('img', { name: '工作人员到岗签到码', exact: true })).toBeVisible();
  await audit.capture('attendance-qr-display');
});

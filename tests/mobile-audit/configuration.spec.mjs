import { test, expect, login, loginApi, navigate, orderFixture } from './support.mjs';
test.skip(process.env.E2E_FIELD !== 'true', 'Requires the disposable field fixture');
const fit = sample => expect.soft(sample.documentWidth, sample.id).toBeLessThanOrEqual(sample.viewport.width + 1);

test('configuration-previews-discard-and-affected-order-navigation', async ({ page, request, audit }, info) => {
  const office = await loginApi(request, '20261001');
  await orderFixture(request, office.token, info);
  await login(page);
  await navigate(page, '预约配置');
  const field = page.locator('input[aria-label$="预约人数"]:visible').first();
  await expect(field).toBeEnabled();
  await field.fill('6');
  await page.getByRole('button', { name: '预览并保存', exact: true }).click();
  await expect(page.getByRole('dialog', { name: '确认预约人数调整' })).toBeVisible();
  fit(await audit.capture('capacity-save-preview', { axe: true }));
  await page.getByRole('dialog').getByRole('button', { name: '关闭', exact: true }).click();
  await navigate(page, '个人中心');
  await expect(page.getByRole('dialog', { name: '有未保存的调整' })).toBeVisible();
  fit(await audit.capture('workspace-unsaved-navigation'));
  await page.getByRole('button', { name: '留在当前页面', exact: true }).click();
  await page.getByRole('button', { name: '放弃修改', exact: true }).click();
  fit(await audit.capture('capacity-discard-confirm'));
  await page.getByRole('button', { name: '确认放弃修改', exact: true }).click();
  await page.getByRole('button', { name: '维修地点', exact: true }).click();
  const location = page.getByRole('textbox', { name: '具体维修地点', exact: true });
  await expect(location).toBeEnabled();
  await location.fill('本地审查临时地点（仅预览，不保存）'.repeat(8));
  await page.getByRole('button', { name: '检查并保存地点', exact: true }).click();
  fit(await audit.capture('location-change-confirm'));
  await page.getByRole('dialog').getByRole('button', { name: '关闭', exact: true }).click();
  await page.getByRole('button', { name: '撤销修改', exact: true }).click();
  await page.getByRole('button', { name: '暂停日期', exact: true }).click();
  await page.getByRole('button', { name: '暂停当天维修', exact: true }).click();
  fit(await audit.capture('service-pause-confirm'));
  await page.getByRole('dialog').getByRole('button', { name: '返回', exact: true }).click();
  await expect(page.getByRole('button', { name: '前往预约记录', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '前往预约记录', exact: true }).click();
  await audit.capture('affected-order-navigation-result');
  await expect.soft(page.locator('.workspace-route:not([hidden])')).toHaveAttribute('data-route', 'staff');
});
